#^ A linked list is a linear data structure consisting of a sequence of nodes,
#^  where each node contains data and a reference (or link) to the next node in the sequence.
#^  Unlike arrays, they are not stored in contiguous memory locations, allowing for efficient insertion and deletion of elements.


#* Key Characteristics and Components:
#* Node Structure: Each node consists of two parts: the data payload and a pointer/reference to the next node.
#* Head Node: The first node in the list, used as the starting point for traversal.
#* Tail Node/Null: The final node, which points to NULL or None, indicating the end of the list.
#* Dynamic Size: Linked lists can grow or shrink in size during execution, as they do not require a predefined memory size. 


#* Common Types of Linked Lists:
#* Singly Linked List: Each node points only to the next node.
#* Doubly Linked List: Each node has references to both the next and the previous node.
#* Circular Linked List: The last node points back to the first node instead of NULL. 

